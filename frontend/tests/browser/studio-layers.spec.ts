import {backendPython} from '../backend-python';
import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import path from 'node:path';

test('real logo drag, watermark, B-roll, music, transitions and caption sync export',async({page})=>{
  test.setTimeout(180000);
  const python=backendPython();
  execFileSync(python,['-m','backend.scripts.browser_fixture']);execFileSync(python,['-m','backend.scripts.studio_fixture']);
  await page.goto('/workspace');
  let downloads=0;page.on('download',()=>downloads++);
  const uploaded=page.waitForResponse(r=>r.url().endsWith('/api/projects')&&r.request().method()==='POST');
  await page.locator('input[type=file]').setInputFiles('artifacts/browser-fixture.mp4');
  const p=await(await uploaded).json(),base=`/api/projects/${p.id}`;
  try{
    expect((await page.request.put(base+'/transcript',{data:[{id:0,start:.2,end:2.8,text:'This is a real studio preview.'}]})).status()).toBe(200);
    await page.request.post(base+'/clips',{data:{title:'Studio layers',start:0,end:3,render_quality:'fast',style:'clean'}});
    await page.reload();
    await page.getByRole('button').filter({has:page.getByRole('heading',{name:'browser-fixture.mp4',exact:true})}).click();
    await page.getByRole('button').filter({has:page.getByText('Studio layers',{exact:true})}).click();
    await page.getByRole('button',{name:'Branding',exact:true}).click();
    await page.getByLabel('Enable text watermark').check();
    await page.getByLabel('Watermark text',{exact:true}).fill('MY CHANNEL');
    await page.getByLabel('Watermark opacity',{exact:true}).fill('0.35');
    const logo=page.waitForResponse(r=>r.url().includes('/assets?kind=logo')&&r.request().method()==='POST');
    await page.getByLabel('Upload logo',{exact:true}).setInputFiles('artifacts/studio-logo.png');
    expect((await logo).status()).toBe(201);
    const handle=page.getByRole('button',{name:'Drag channel logo'});
    await expect(handle).toBeVisible();
    await handle.scrollIntoViewIfNeeded();
    const before=Number(await page.getByLabel('Logo X',{exact:true}).inputValue());
    const box=await handle.boundingBox();
    await page.mouse.move(box!.x+box!.width/2,box!.y+box!.height/2);await page.mouse.down();await page.mouse.move(box!.x+box!.width/2-80,box!.y+box!.height/2+45,{steps:6});await page.mouse.up();
    expect(Number(await page.getByLabel('Logo X',{exact:true}).inputValue())).toBeLessThan(before);
    await page.getByRole('button',{name:'Drag text watermark'}).focus();await page.keyboard.press('Shift+ArrowUp');
    expect(Number(await page.getByLabel('Watermark Y',{exact:true}).inputValue())).toBeLessThan(50);
    await page.screenshot({animations:'disabled',path:'artifacts/studio-branding-desktop.png',fullPage:true});
    await page.getByRole('button',{name:'B-roll & images',exact:true}).click();
    const broll=page.waitForResponse(r=>r.url().includes('/assets?kind=filler')&&r.request().method()==='POST');
    await page.getByLabel('Upload filler',{exact:true}).setInputFiles('artifacts/studio-broll.mp4');expect((await broll).status()).toBe(201);
    await page.getByLabel('B-roll start',{exact:true}).fill('0.7');await page.getByLabel('B-roll end',{exact:true}).fill('1.8');
    await page.getByLabel('B-roll layout',{exact:true}).selectOption('pip');
    const photo=page.waitForResponse(r=>r.url().includes('/assets?kind=image')&&r.request().method()==='POST');
    await page.getByLabel('Upload image',{exact:true}).setInputFiles('artifacts/studio-logo.png');expect((await photo).status()).toBe(201);
    await page.getByLabel('Photo start',{exact:true}).fill('0.8');await page.getByLabel('Photo end',{exact:true}).fill('1.6');
    await page.getByRole('button',{name:'Audio',exact:true}).click();
    const music=page.waitForResponse(r=>r.url().includes('/assets?kind=music')&&r.request().method()==='POST');
    await page.getByLabel('Upload music',{exact:true}).setInputFiles('artifacts/studio-music.wav');expect((await music).status()).toBe(201);
    await page.getByLabel('Sound effect',{exact:true}).selectOption('ding');await page.getByLabel('Sound starts',{exact:true}).fill('1.1');
    await page.getByRole('button',{name:'Effects',exact:true}).click();
    await page.getByLabel('Video effect',{exact:true}).selectOption('cinematic');
    await page.getByLabel('Transition',{exact:true}).selectOption('fade');
    await page.getByRole('button',{name:'Captions',exact:true}).click();
    await page.getByLabel('Caption sync',{exact:true}).fill('0.25');
    await page.getByRole('button',{name:'Apply & render',exact:true}).click();
    await expect(page.getByRole('button',{name:'Export ready',exact:true})).toBeVisible({timeout:60000});
    await expect.poll(()=>page.locator('.video-stage video').evaluate((v:HTMLVideoElement)=>v.readyState)).toBeGreaterThanOrEqual(1);
    const saved=(await(await page.request.get(base)).json()).clips[0];
    expect(saved).toMatchObject({watermark_enabled:true,watermark_text:'MY CHANNEL',watermark_opacity:.35,filler_layout:'pip',transition:'fade',video_effect:'cinematic',sound_effect:'ding',caption_offset:.25});
    expect(saved.logo_asset_id).toBeTruthy();expect(saved.music_asset_id).toBeTruthy();expect(saved.image_asset_id).toBeTruthy();
    expect(await(await page.request.get(base+'/subtitles?clip_id='+saved.id)).text()).toContain('00:00:00,450');
    const video=await page.request.get(base+'/media/'+saved.id);expect(video.status()).toBe(200);
    require('node:fs').writeFileSync('artifacts/studio-browser-export.mp4',await video.body());
    for(const width of [1440,1024,768,390]){
      await page.setViewportSize({width,height:900});
      expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
    }
    await page.getByRole('button',{name:'Branding',exact:true}).click();
    await expect(handle).toBeVisible();await page.screenshot({animations:'disabled',path:'artifacts/studio-branding-mobile.png',fullPage:true});
    expect(downloads).toBe(0);
  }finally{await page.request.delete(base).catch(()=>{});}
});
